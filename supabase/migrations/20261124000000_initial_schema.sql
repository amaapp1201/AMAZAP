-- ---------------------------------------------------------------------------
-- 権限
-- ---------------------------------------------------------------------------
-- next_auth はサーバー側（service_role）からのみ読み書きする。
-- authenticated にはポリシー内の補助関数を呼ぶための USAGE だけを与え、テーブルは見せない。
grant usage on schema next_auth to service_role, authenticated;
grant all on all tables in schema next_auth to service_role;
grant execute on all functions in schema next_auth to service_role, authenticated;

-- public はログイン済みユーザー（authenticated）と service_role のみ。実際の可否は RLS が決める。
grant usage on schema public to authenticated, service_role;
grant select, insert, update, delete on all tables in schema public to authenticated;
grant all on all tables in schema public to service_role;
grant usage, select on all sequences in schema public to authenticated, service_role;
grant execute on all functions in schema public to authenticated, service_role;

-- 未ログイン（anon）には何も見せない。
-- ビューは RLS を通らないため、明示的に外しておく。
revoke all on all tables in schema public from anon;
revoke execute on all functions in schema public from anon, public;
revoke execute on all functions in schema next_auth from anon, public;

commit;
