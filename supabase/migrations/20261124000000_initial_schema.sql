-- JWT の中身を読む補助関数（RLS のポリシーから使う）
create function next_auth.uid() returns uuid
language sql stable
as $$
  select
    coalesce(
      nullif(current_setting('request.jwt.claim.sub', true), ''),
      (nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'sub')
    )::uuid
$$;

-- 元は IMMUTABLE だったが、リクエストごとに値が変わるため STABLE にしている
create function next_auth.is_admin() returns boolean
language plpgsql stable
as $$
begin
  return (
    coalesce(
      nullif(current_setting('request.jwt.claim.isAdmin', true), ''),
      (nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'isAdmin')
    )
  )::boolean;
end;
$$;

