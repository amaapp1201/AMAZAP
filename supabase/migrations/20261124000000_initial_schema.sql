create function public.bulk_update_action_categories(updates jsonb)
returns void
language plpgsql
as $$
begin
  update action_categories
  set
    order_id = u.order_id
  from (
    select
      (value->>'id')::int as id,
      (value->>'order_id')::int as order_id
    from jsonb_array_elements(updates) as value
  ) as u
  where action_categories.id = u.id;
end;
$$;

create function public.bulk_update_actions(updates jsonb)
returns void
language plpgsql
as $$
begin
  update actions
  set
    category_id = u.category_id,
    order_id = u.order_id
  from (
    select
      (value->>'id')::int as id,
      (value->>'category_id')::int as category_id,
      (value->>'order_id')::int as order_id
    from jsonb_array_elements(updates) as value
  ) as u
  where actions.id = u.id;
end;
$$;

create function public.get_team_action_point_summary(p_event_id bigint)
returns table (team_id bigint, team_name text, total_action_point bigint, total_step bigint)
language plpgsql
as $$
begin
  return query
  select
    ur.snapshot_team_id,
    et.name_snapshot as team_name,
    sum(ur.today_action_point_summary + ur.last_action_point_cumulative) as total_action_point,
    sum(ur.today_step_summary + ur.last_step_cumulative) as total_step
  from
    records ur
  join (
    select
      user_id,
      max(date) as max_date
    from
      records
    where
      event_id = p_event_id
    group by
      user_id
  ) latest_records on ur.user_id = latest_records.user_id and ur.date = latest_records.max_date
  join
    event_teams et on et.event_id = ur.event_id and et.team_id = ur.snapshot_team_id
  group by
    ur.snapshot_team_id, et.name_snapshot;
end;
$$;

create function public.get_user_action_point_summary(p_event_id bigint)
returns table (user_id uuid, user_name text, team_name text, total_action_point bigint, total_step bigint)
language plpgsql
as $$
begin
  return query
  select
    ur.user_id as user_id,
    u.name as user_name,
    et.name_snapshot as team_name,
    sum(ur.today_action_point_summary + ur.last_action_point_cumulative) as total_action_point,
    sum(ur.today_step_summary + ur.last_step_cumulative) as total_step
  from
    records ur
  join (
    select
      lr.user_id,
      max(lr.date) as max_date
    from
      records lr
    where
      lr.event_id = p_event_id
    group by
      lr.user_id
  ) latest_records
  on ur.user_id = latest_records.user_id and ur.date = latest_records.max_date
  join
    event_teams et on et.event_id = ur.event_id and et.team_id = ur.snapshot_team_id
  join
    next_auth.users u on u.id = ur.user_id
  group by
    ur.user_id, u.name, et.name_snapshot;
end;
$$;

create function public.insert_event_actions_snapshot(p_event_id bigint)
returns void
language plpgsql
as $$
begin
  insert into event_actions_snapshot (event_id, action_id, name, category_id, order_id, point)
  select
    p_event_id,
    actions.id,
    actions.name,
    actions.category_id,
    actions.order_id,
    actions.point
  from actions
  join event_categories
  on actions.category_id = event_categories.category_id
  where event_categories.event_id = p_event_id;
end;
$$;

create function public.insert_event_users_snapshot(p_event_id bigint)
returns void
language plpgsql
as $$
begin
  insert into event_users_snapshot (event_id, user_id, team_id, name)
  select
    p_event_id,
    next_auth.users.id,
    next_auth.users.team_id,
    next_auth.users.name
  from next_auth.users
  join event_teams
  on next_auth.users.team_id = event_teams.team_id
  where event_teams.event_id = p_event_id;
end;
$$;

create function public.update_event_category_snapshot(p_event_id bigint)
returns void
language plpgsql
as $$
begin
  update event_categories
  set name_snapshot = action_categories.name,
      order_id_snapshot = action_categories.order_id,
      is_single_selection_snapshot = action_categories.is_single_selection
  from action_categories
  where event_categories.category_id = action_categories.id
    and event_categories.event_id = p_event_id;
end;
$$;

create function public.update_event_teams_snapshot(p_event_id bigint)
returns void
language plpgsql
as $$
begin
  update event_teams
  set name_snapshot = teams.name
  from teams
  where event_teams.team_id = teams.id
    and event_teams.event_id = p_event_id;
end;
$$;

