create view public.event_view as
select
  events.id,
  events.created_at,
  events.name,
  events."startAt",
  events."endAt",
  events.status,
  events.is_team_rank_visible as is_rank_visible,
  (select json_agg(event_categories.*)
     from public.event_categories
    where event_categories.event_id = events.id) as event_categories,
  (select json_agg(event_teams.*)
     from public.event_teams
    where event_teams.event_id = events.id) as event_teams
from public.events;

create view public.user_teams_view as
select
  users.id as user_id,
  users.name as user_name,
  users.team_id,
  teams.name as team_name,
  users.is_admin
from next_auth.users users
left join public.teams on users.team_id = teams.id;

